#!/usr/bin/env node
// Lists every fact the owner still has to supply or confirm (TODO_OWNER, verified: false, unconfirmed photo rights).
// Claude Code copies this output into docs/BUILD-REPORT.md at the end of each phase.
import { loadVilla, loadPhotos } from './lib/site.mjs';

const villa = loadVilla();
const todo = [];
const unverified = [];
(function scan(node, trail) {
  if (node === 'TODO_OWNER') return todo.push(trail.join('.'));
  if (Array.isArray(node)) return node.forEach((v, i) => scan(v, [...trail, v?.id || v?.name || v?.place || i]));
  if (node && typeof node === 'object') {
    if (node.verified === false) unverified.push(trail.join('.'));
    for (const [k, v] of Object.entries(node)) scan(v, [...trail, k]);
  }
})(villa, []);
const photos = (loadPhotos().photos || []).filter((p) => p.rights !== 'owner' && p.rights !== 'licensed').map((p) => p.file);

console.log('# Owner to-do (generated by scripts/owner-todo.mjs)\n');
console.log(`## Missing facts (TODO_OWNER): ${todo.length}`);
todo.forEach((t) => console.log(`- [ ] ${t}`));
console.log(`\n## Facts from a single source, to confirm: ${unverified.length}`);
unverified.forEach((t) => console.log(`- [ ] ${t}`));
console.log(`\n## Photos with unconfirmed rights (not published): ${photos.length}`);
photos.forEach((f) => console.log(`- [ ] ${f}`));
